def guide_html(path):
    g = TOOL_GUIDES.get(path)
    if not g:
        return ""
    items = "".join(f'<details class="faq-item"><summary>{q}</summary><div>{a}</div></details>' for q, a in g["faq"])
    return (f'<section class="section section--tight tool-guide"><div class="wrap"><article class="article">{g["body"]}'
            f'<h2 id="faq">자주 묻는 질문</h2><div class="faq-list">{items}</div></article></div></section>')


